def build(idx, locale, note=None):
    d = {"@@locale": locale}
    if note:
        d["@@x-status"] = note
    for k, v in S.items():
        d[k] = v[idx]
    for k, (vals, ph) in PARAM.items():
        d[k] = vals[idx]
        if idx == 0:
            d["@" + k] = {"placeholders": ph}
    return d

